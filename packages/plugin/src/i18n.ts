export const dictionaries: Record<string, Record<Key, string>> = { en, pt };
let current: Record<Key, string> = en;
let locale = 'en';

/** `pt`, `pt-BR`, `pt_BR` → Portuguese; anything else → English. */
export function setLanguage(lang: string | null | undefined): void {
  const code = (lang ?? 'en').toLowerCase().split(/[-_]/)[0] ?? 'en';
  current = dictionaries[code] ?? en;
  locale = dictionaries[code] ? code : 'en';
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  const s = current[key] ?? en[key];
  return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : s;
}

/** Relative time ("3 days ago") in the active language. */
export function timeAgo(iso: string | undefined, now: Date): string {
  const at = iso ? Date.parse(iso) : NaN;
  if (!Number.isFinite(at)) return '';
  const diff = (at - now.getTime()) / 1000;
  const rtf = new Intl.RelativeTimeFormat(locale, { numeric: 'auto' });
  const units: [Intl.RelativeTimeFormatUnit, number][] = [
    ['year', 31_536_000],
    ['month', 2_592_000],
    ['week', 604_800],
    ['day', 86_400],
    ['hour', 3_600],
    ['minute', 60],
  ];
  for (const [unit, secs] of units) {
    if (Math.abs(diff) >= secs) return rtf.format(Math.round(diff / secs), unit);
  }
  return rtf.format(0, 'second');
}

export const getLocale = (): string => locale;
